function buildModuleCategories() {
  return MODULE_DEFINITIONS.map((def) => {
    const dirFullPath = path.join(__dirname, def.dirName);
    const hasFiles =
      fs.existsSync(dirFullPath) &&
      fs.readdirSync(dirFullPath).some((f) => f.endsWith('.md') || f.endsWith('.mdx'));

    if (hasFiles) {
      return {
        type: 'category' as const,
        label: def.label,
        link: {
          type: 'generated-index' as const,
          title: def.label,
          description: def.description,
          slug: def.slug,
        },
        items: [
          {
            type: 'autogenerated' as const,
            dirName: def.dirName,
          },
        ],
      };
    }

    // Gracefully resolve planned modules to curriculum intro until authored
    return {
      type: 'category' as const,
      label: def.label,
      link: {
        type: 'doc' as const,
        id: 'intro',
      },
      items: ['intro'],
    };
  });
}


"""
Agent Service — RAG Agent built on Google Gemini with function calling.

The agent operates in a tool-calling loop (max 5 turns):
1. Send user query → LLM decides whether to call ``retrieve_chunks``.
2. Execute the tool against the Qdrant vector DB.
3. Feed tool output back → LLM synthesises a grounded answer.
4. Return final text response with source citations.

The system prompt explicitly instructs the model to answer *only* from
retrieved content and to admit when information is unavailable.
"""

import google.genai as genai
from google.genai import types
from pydantic import BaseModel, Field

from app.core.config import settings
from app.core.logging import get_logger

from ..retriever.retriever_service import RetrieverService
from ..schemas.chat_models import ChatResponse

logger = get_logger(__name__)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

SYSTEM_PROMPT = """You are a helpful AI assistant for the book "Physical AI & Humanoid Robotics".
Your ONLY source of knowledge is the content retrieved from the book's vector database.

RULES (non-negotiable):
1. Always call the `retrieve_chunks` tool before answering any question.
2. Base your answer exclusively on the retrieved content. Do NOT use external knowledge.
3. If the retrieved content does not contain the answer, say:
   "I could not find relevant information in the book to answer that question."
4. When you use content from the book, cite the source URL(s) at the end of your response.
5. Keep answers clear, educational, and concise."""


MAX_AGENT_TURNS = 5

MODEL_NAME = "gemini-2.5-flash"

# Tool declaration for the retrieve_chunks function using the new SDK
RETRIEVE_CHUNKS_TOOL = types.Tool(
    function_declarations=[
        types.FunctionDeclaration(
            name="retrieve_chunks",
            description=(
                "Retrieves relevant content chunks from the book's Qdrant knowledge base "
                "based on a semantic similarity search. Always call this tool first."
            ),
            parameters=types.Schema(
                type="OBJECT",
                properties={
                    "query_text": types.Schema(
                        type="STRING",
                        description="The user's query or question to retrieve relevant information for.",
                    ),
                    "top_k": types.Schema(
                        type="INTEGER",
                        description="Maximum number of content chunks to retrieve.",
                    ),
                },
                required=["query_text"],
            ),
        )
    ]
)

# GenerateContentConfig used for every call in the agent loop
GENERATE_CONFIG = types.GenerateContentConfig(
    system_instruction=SYSTEM_PROMPT,
    tools=[RETRIEVE_CHUNKS_TOOL],
)


# ---------------------------------------------------------------------------
# Internal Pydantic models (not part of the API schema)
# ---------------------------------------------------------------------------


class ToolOutput(BaseModel):
    """Represents the result of executing a single tool call."""

    tool_name: str = Field(..., description="Name of the tool that was called.")
    output: str = Field(..., description="String output generated by the tool.")


# ---------------------------------------------------------------------------
# AgentService
# ---------------------------------------------------------------------------


class AgentService:
    """
    Wraps the Google Gemini API (via the ``google-genai`` SDK) and the custom
    ``retrieve_chunks`` tool to provide a fully grounded RAG agent.
    """

    def __init__(self):
        self.gemini_client = genai.Client(api_key=settings.GEMINI_API_KEY)
        self.retriever_service = RetrieverService()
        self.model = MODEL_NAME

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _call_tool(self, function_call: types.FunctionCall) -> ToolOutput:
        """
        Dispatches a tool call received from the LLM and returns its output.

        Args:
            function_call: A Gemini ``FunctionCall`` object from the response.

        Returns:
            A :class:`ToolOutput` with the tool name and string result.
        """
        tool_name = function_call.name
        tool_arguments = dict(function_call.args) if function_call.args else {}

        if tool_name == "retrieve_chunks":
            query_text = tool_arguments.get("query_text")
            top_k = int(tool_arguments.get("top_k", 5))

            if not query_text:
                return ToolOutput(
                    tool_name="retrieve_chunks",
                    output="Error: query_text is required for retrieve_chunks tool.",
                )

            logger.info(
                f"AgentService: calling retrieve_chunks — query='{query_text}', top_k={top_k}"
            )
            chunks = self.retriever_service.retrieve_chunks(
                query_text=query_text, top_k=top_k
            )

            if not chunks:
                return ToolOutput(
                    tool_name="retrieve_chunks",
                    output="No relevant information found in the knowledge base for this query.",
                )

            formatted_chunks = "\n\n".join(
                f"Source: {chunk.source_url}\nContent: {chunk.original_text}"
                for chunk in chunks
            )
            logger.info(
                f"AgentService: retrieve_chunks returned {len(chunks)} chunks."
            )
            return ToolOutput(tool_name="retrieve_chunks", output=formatted_chunks)

        # Unknown tool
        logger.warning(f"AgentService: unknown tool requested — '{tool_name}'")
        return ToolOutput(tool_name=tool_name, output=f"Error: Unknown tool '{tool_name}'")

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def ask_agent(self, user_query: str) -> ChatResponse:
        """
        Runs the RAG agent loop for a single user query.

        The agent will:
        1. Call ``retrieve_chunks`` to fetch grounding context.
        2. Synthesise an answer from the retrieved content.
        3. Return a :class:`ChatResponse` with the answer and source citations.

        Args:
            user_query: The user's natural-language question.

        Returns:
            A :class:`ChatResponse` with ``answer_text`` and ``retrieved_sources``.
        """
        logger.info(f"AgentService.ask_agent — query: '{user_query}'")

        # Build the initial conversation history
        contents: list[types.Content] = [
            types.Content(
                role="user",
                parts=[types.Part(text=user_query)],
            )
        ]

        retrieved_sources: list[str] = []

        for turn in range(MAX_AGENT_TURNS):
            logger.info(f"AgentService: turn {turn + 1}/{MAX_AGENT_TURNS}")

            response = self.gemini_client.models.generate_content(
                model=self.model,
                contents=contents,
                config=GENERATE_CONFIG,
            )

            # --- Check for function calls in this response ---
            function_calls = []
            for candidate in response.candidates or []:
                for part in candidate.content.parts or []:
                    if part.function_call and part.function_call.name:
                        function_calls.append(part.function_call)

            if function_calls:
                # Append the model's tool-call turn to history by reusing the
                # candidate Content directly — this avoids re-constructing
                # types.Part objects from proto objects and is safer.
                model_content = response.candidates[0].content
                contents.append(model_content)

                # Execute each tool and collect results
                tool_result_parts: list[types.Part] = []
                for fc in function_calls:
                    tool_output = self._call_tool(fc)

                    # Collect unique source URLs
                    if (
                        tool_output.tool_name == "retrieve_chunks"
                        and "Source:" in tool_output.output
                    ):
                        for line in tool_output.output.split("\n"):
                            if line.startswith("Source:"):
                                source = line.replace("Source: ", "").strip()
                                if source and source not in retrieved_sources:
                                    retrieved_sources.append(source)

                    tool_result_parts.append(
                        types.Part(
                            function_response=types.FunctionResponse(
                                name=fc.name,
                                response={"result": tool_output.output},
                            )
                        )
                    )

                # Append tool results as a "user" turn (function response role)
                contents.append(
                    types.Content(role="user", parts=tool_result_parts)
                )
                continue  # Next turn — let the model synthesise an answer

            # --- No function calls: extract the final text answer ---
            answer_text = ""
            try:
                answer_text = response.text.strip() if response.text else ""
            except Exception:
                # response.text may raise if there are no text parts
                for candidate in response.candidates or []:
                    for part in candidate.content.parts or []:
                        if part.text:
                            answer_text = part.text.strip()
                            break
                    if answer_text:
                        break

            if answer_text:
                logger.info(
                    f"AgentService: final answer (turn {turn + 1}): "
                    f"'{answer_text[:120]}...'"
                )
                logger.info(f"AgentService: sources — {retrieved_sources}")
                return ChatResponse(
                    answer_text=answer_text,
                    retrieved_sources=retrieved_sources,
                )
            else:
                logger.warning(
                    "AgentService: empty response from LLM — returning fallback."
                )
                return ChatResponse(
                    answer_text="I could not generate a response. Please try again.",
                    retrieved_sources=[],
                )

        logger.error(
            f"AgentService: exceeded {MAX_AGENT_TURNS} turns without a final answer."
        )
        return ChatResponse(
            answer_text="I could not generate a response after multiple attempts. Please try again.",
            retrieved_sources=[],
        )


